# --- КЛАВИАТУРЫ ---

def get_main_keyboard() -> InlineKeyboardMarkup:
    buttons = [
        [InlineKeyboardButton(text=info["title"], callback_data=f"cat:{cat_key}")]
        for cat_key, info in DATA.items()
    ]
    return InlineKeyboardMarkup(inline_keyboard=buttons)


def get_subcategories_keyboard(category_key: str) -> InlineKeyboardMarkup:
    subcats = DATA[category_key]["subcategories"]
    buttons = [
        [InlineKeyboardButton(text=info["title"], callback_data=f"item:{category_key}:{item_key}")]
        for item_key, info in subcats.items()
    ]
    buttons.append([InlineKeyboardButton(text="⬅️ В главное меню", callback_data="back_to_main")])
    return InlineKeyboardMarkup(inline_keyboard=buttons)


def get_back_keyboard(category_key: str) -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(
        inline_keyboard=[
            [InlineKeyboardButton(text="⬅️ Назад к списку", callback_data=f"cat:{category_key}")],
            [InlineKeyboardButton(text="🏠 В главное меню", callback_data="back_to_main")],
        ]
    )

# --- ОБРАБОТЧИКИ ---

@dp.message(CommandStart())
async def cmd_start(message: Message) -> None:
    text = (
        "👋 **Привет! Я бот «ПравоКомпас».**\n\n"
        "Здесь ты можешь узнать, какая ответственность и последствия "
        "предусмотрены законом РФ за различные проступки и правонарушения.\n\n"
        "Выбери нужный раздел:"
    )
    await message.answer(text, reply_markup=get_main_keyboard(), parse_mode=ParseMode.MARKDOWN)


@dp.callback_query(F.data == "back_to_main")
async def back_to_main(callback: CallbackQuery) -> None:
    text = "👋 Выбери раздел правонарушений:"
    await callback.message.edit_text(text, reply_markup=get_main_keyboard())
    await callback.answer()


@dp.callback_query(F.data.startswith("cat:"))
async def show_category(callback: CallbackQuery) -> None:
    category_key = callback.data.split(":")[1]
    cat_data = DATA.get(category_key)
    if not cat_data:
        await callback.answer("Раздел не найден", show_alert=True)
        return

    text = f"Раздел: **{cat_data['title']}**\n\nВыбери ситуацию:"
    await callback.message.edit_text(
        text,
        reply_markup=get_subcategories_keyboard(category_key),
        parse_mode=ParseMode.MARKDOWN,
    )
    await callback.answer()


@dp.callback_query(F.data.startswith("item:"))
async def show_item(callback: CallbackQuery) -> None:
    _, cat_key, item_key = callback.data.split(":")
    item_data = DATA.get(cat_key, {}).get("subcategories", {}).get(item_key)

    if not item_data:
        await callback.answer("Информация не найдена", show_alert=True)
        return

    await callback.message.edit_text(
        item_data["text"],
        reply_markup=get_back_keyboard(cat_key),
        parse_mode=ParseMode.MARKDOWN,
    )
    await callback.answer()

